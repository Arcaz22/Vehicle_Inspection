CREATE TABLE vehicles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plate_number VARCHAR(16) NOT NULL UNIQUE,
    type VARCHAR(32) NOT NULL,
    brand VARCHAR(80) NOT NULL,
    model VARCHAR(80) NOT NULL,
    year INTEGER NOT NULL CHECK (year BETWEEN 1900 AND 2100)
);

CREATE TABLE inspections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id BIGINT NOT NULL REFERENCES vehicles(id),
    client_id UUID UNIQUE,
    inspector_name VARCHAR(160) NOT NULL,
    has_key BOOLEAN NOT NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'DRAFT'
        CHECK (status IN ('DRAFT', 'SUBMITTED', 'APPROVED', 'RECHECK')),
    version BIGINT NOT NULL DEFAULT 1 CHECK (version >= 1),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE inspection_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inspection_id BIGINT NOT NULL REFERENCES inspections(id) ON DELETE CASCADE,
    point_code VARCHAR(64) NOT NULL,
    condition VARCHAR(32) NOT NULL
        CHECK (condition IN ('GOOD', 'MINOR_DAMAGE', 'MAJOR_DAMAGE', 'NOT_INSPECTABLE')),
    note TEXT,
    photo_refs JSONB NOT NULL DEFAULT '[]'::jsonb,
    CONSTRAINT uq_inspection_item_point UNIQUE (inspection_id, point_code)
);

